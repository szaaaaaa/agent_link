import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { access, link, lstat, mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { isDeepStrictEqual } from "node:util";
import { autostartPlan, windowsSid } from "./autostart.js";

const managed = "// Generated by agent-link install\n";
const events = ["SessionStart", "PreInvocation", "Stop"] as const;
const missing = (error: unknown) => (error as NodeJS.ErrnoException).code === "ENOENT";

async function existing(path: string): Promise<string | null> {
  try {
    if (!(await lstat(path)).isFile()) throw new Error(`Refusing to replace a non-regular file: ${path}`);
    return await readFile(path, "utf8");
  } catch (error) { if (missing(error)) return null; throw error; }
}

async function publish(path: string, text: string, previous: string | null): Promise<void> {
  if (text === previous) return;
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  const tmp = path + "." + randomUUID() + ".tmp";
  try {
    await writeFile(tmp, text, { flag: "wx", mode: 0o600 });
    if (previous === null) await link(tmp, path);
    else {
      if (await existing(path) !== previous) throw new Error(`Changed during installation; retry: ${path}`);
      await rename(tmp, path);
    }
  } finally { await rm(tmp, { force: true }); }
}

export function agyHookCommand(node: string, bootstrap: string, event: typeof events[number]): string {
  if (process.platform === "win32") {
    for (const path of [node, bootstrap]) {
      if (/[\r\n"%!^&]/.test(path)) {
        throw new Error(`Path cannot be safely quoted for Antigravity cmd hooks: ${path}`);
      }
    }
    return `call "${node}" "${bootstrap}" hook ${event}`;
  }
  const quote = (value: string) => "'" + value.replaceAll("'", "'\\''") + "'";
  return `${quote(node)} ${quote(bootstrap)} hook ${event}`;
}

export async function install(dir: string, cli: string, enableAutostart: boolean) {
  const home = homedir();
  const source = resolve(dirname(cli), "../integrations/pi-extension/index.ts");
  await access(source);
  const pi = join(resolve(process.env.PI_CODING_AGENT_DIR || join(home, ".pi", "agent")), "extensions", "agent-link.ts");
  const hooks = join(home, ".gemini", "config", "hooks.json");
  const boot = join(dir, "launcher.cjs");
  const config = join(dir, "config.json");
  const [oldPi, oldHooks, oldBoot, oldConfig] = await Promise.all([pi, hooks, boot, config].map(existing));
  for (const [path, content] of [[pi, oldPi], [boot, oldBoot]]) {
    if (content !== null && !content.startsWith(managed)) throw new Error(`Refusing to overwrite unmanaged file: ${path}`);
  }
  let hookConfig: Record<string, unknown>;
  try {
    const value = oldHooks === null ? {} : JSON.parse(oldHooks.trim());
    if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("not a JSON object");
    hookConfig = value;
  } catch { throw new Error(`Refusing to overwrite invalid JSON config: ${hooks}`); }
  const group = Object.fromEntries(events.map((event) => [event, [{ type: "command",
    command: agyHookCommand(process.execPath, boot, event), timeout: 5 }]]));
  const current = hookConfig["agent-link"];
  if (Object.hasOwn(hookConfig, "agent-link")) {
    if (!current || typeof current !== "object" || Array.isArray(current)) throw new Error(`Unmanaged agent-link hook in ${hooks}`);
    const { enabled, ...handlers } = current as Record<string, unknown>;
    if ((enabled !== undefined && typeof enabled !== "boolean") || !isDeepStrictEqual(handlers, group)) {
      throw new Error(`Refusing to overwrite unmanaged agent-link hook in ${hooks}`);
    }
  }
  const autostart = enableAutostart ? autostartPlan(process.platform, home, dir, process.execPath, boot,
    process.platform === "win32" ? windowsSid() : undefined) : null;
  const oldAutostart = autostart ? await existing(autostart.path) : null;
  if (autostart && oldAutostart !== null && oldAutostart !== autostart.body) {
    throw new Error(`Refusing to overwrite unmanaged autostart file: ${autostart.path}`);
  }

  if (oldConfig === null) await publish(config, '{"workspaces":[]}\n', null);
  await publish(boot, managed + `process.env.AGENT_LINK_HOME = ${JSON.stringify(dir)};\n` +
    `process.argv[1] = ${JSON.stringify(cli)};\n` +
    `import(${JSON.stringify(pathToFileURL(cli).href)}).catch((error) => { console.error(error); process.exitCode = 1; });\n`, oldBoot);
  await publish(pi, managed + `import agentLink from ${JSON.stringify(pathToFileURL(source).href)};\n` +
    `export default (pi) => agentLink(pi, ${JSON.stringify(dir)});\n`, oldPi);
  if (!current) {
    const backup = join(dir, "hooks.before-agent-link.json");
    if (oldHooks !== null && await existing(backup) === null) await publish(backup, oldHooks, null);
    await publish(hooks, JSON.stringify({ ...hookConfig, "agent-link": group }, null, 2) + "\n", oldHooks);
  }
  if (autostart) {
    await publish(autostart.path, autostart.body, oldAutostart);
    const [command, ...args] = autostart.command;
    if (command) execFileSync(command, args, { stdio: "pipe", timeout: 10_000, windowsHide: true });
  }
  return { data_dir: dir, pi_extension: pi, antigravity_hooks: hooks,
    autostart: autostart ? { id: autostart.id, path: autostart.path } : null };
}
