import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { autostartPlan } from "../dist/autostart.js";

const cli = fileURLToPath(new URL("../dist/cli.js", import.meta.url));
const probe = fileURLToPath(new URL("../scripts/probe-agy.mjs", import.meta.url));
const read = (path) => readFileSync(path, "utf8");
const json = (path) => JSON.parse(read(path));

function sandbox(t) {
  const home = mkdtempSync(join(tmpdir(), "agent link install-"));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const dir = join(home, "Agent Link Data");
  const piHome = join(home, "Pi custom home");
  const config = join(home, ".gemini", "config", "hooks.json");
  const env = { ...process.env, HOME: home, USERPROFILE: home, AGENT_LINK_HOME: dir, PI_CODING_AGENT_DIR: piHome };
  return { home, dir, config, pi: join(piHome, "extensions", "agent-link.ts"), env,
    install: () => spawnSync(process.execPath, [cli, "install"], { env, encoding: "utf8" }) };
}

function shell(command, cwd, input, env) {
  return process.platform === "win32"
    ? spawnSync(process.env.ComSpec || "cmd.exe", ["/d", "/c", command], { cwd, input, env,
      encoding: "utf8", windowsVerbatimArguments: true, timeout: 5000 })
    : spawnSync("/bin/sh", ["-c", command], { cwd, input, env, encoding: "utf8", timeout: 5000 });
}

test("install merges named hooks, preserves existing state and runs the installed command from a shell", (t) => {
  const box = sandbox(t);
  mkdirSync(dirname(box.config), { recursive: true });
  const old = { "personal-lint": { enabled: false, PreInvocation: [{ command: "user command", timeout: 10 }] } };
  const previous = JSON.stringify(old) + "\n";
  writeFileSync(box.config, previous);
  const installed = box.install();
  assert.equal(installed.status, 0, installed.stderr);
  const output = JSON.parse(installed.stdout);
  assert.equal(output.pi_extension, box.pi);
  assert.equal(output.autostart, null);
  assert.equal(read(join(box.dir, "hooks.before-agent-link.json")), previous);
  assert.equal(read(join(box.dir, "config.json")), '{"workspaces":[]}\n');
  const hooks = json(box.config);
  assert.deepEqual(hooks["personal-lint"], old["personal-lint"]);
  assert.deepEqual(Object.keys(hooks["agent-link"]), ["SessionStart", "PreInvocation", "Stop"]);
  assert.equal(hooks["agent-link"].Stop[0].timeout, 5);
  assert.equal(existsSync(join(box.dir, "daemon.pid")), false);
  assert.equal(existsSync(join(box.dir, "autostart.xml")), false);
  assert.equal(existsSync(join(box.home, "Library", "LaunchAgents")), false);
  assert.match(read(box.pi), /^\/\/ Generated by agent-link install/);

  const fromClient = { ...box.env, AGENT_LINK_HOME: join(box.home, "unrelated data") };
  const result = shell(hooks["agent-link"].Stop[0].command, dirname(box.config), "{}", fromClient);
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(JSON.parse(result.stdout), { decision: "stop" });
  hooks["agent-link"].enabled = false;
  writeFileSync(box.config, JSON.stringify(hooks) + "\n");
  const edited = read(box.config);
  const configText = '{"workspaces":[{"workspace_key":"keep-me"}]}\n';
  writeFileSync(join(box.dir, "config.json"), configText);
  assert.equal(box.install().status, 0);
  assert.equal(read(box.config), edited);
  assert.equal(read(join(box.dir, "config.json")), configText);
});

test("install refuses invalid config or unmanaged collisions before changing files", (t) => {
  const box = sandbox(t);
  mkdirSync(dirname(box.config), { recursive: true });
  writeFileSync(box.config, "{invalid");
  assert.match(box.install().stderr, /invalid JSON config/);
  assert.equal(read(box.config), "{invalid");
  assert.equal(existsSync(box.dir), false);
  writeFileSync(box.config, '{"agent-link":{"Stop":[{"command":"personal"}]}}');
  assert.match(box.install().stderr, /unmanaged agent-link hook/);
  assert.equal(existsSync(box.pi), false);
  writeFileSync(box.config, "{}");
  mkdirSync(dirname(box.pi), { recursive: true });
  writeFileSync(box.pi, "export default () => {};");
  assert.match(box.install().stderr, /unmanaged file/);
  assert.equal(read(box.pi), "export default () => {};");
  assert.equal(read(box.config), "{}");
  assert.equal(existsSync(box.dir), false);
});

test("opt-in autostart plans run the same daemon for the current user", () => {
  const root = join(tmpdir(), "home with spaces");
  const dir = join(root, "data");
  const entry = join(dir, "launcher.cjs");
  const win = autostartPlan("win32", root, dir, process.execPath, entry, "S-1-5-21-123");
  assert.match(win.body, /<UserId>S-1-5-21-123<\/UserId>.*<\/LogonTrigger>/);
  assert.match(win.body, /InteractiveToken.*LeastPrivilege/);
  assert.match(win.body, /&quot; daemon run/);
  assert.deepEqual(win.command.slice(0, 4).slice(1), ["/Create", "/TN", win.id]);
  const mac = autostartPlan("darwin", root, dir, process.execPath, entry);
  assert.match(mac.path, /LaunchAgents/);
  assert.match(mac.body, /<key>RunAtLoad<\/key><true\/>/);
  assert.match(mac.body, /<string>daemon<\/string>\s+<string>run<\/string>/);
  const linux = autostartPlan("linux", root, dir, process.execPath, join(dir, "$x%t.cjs"));
  assert.match(linux.body, /ExecStart=.*\$\$x%%t\.cjs" daemon run/);
  assert.deepEqual(linux.command, ["systemctl", "--user", "enable", linux.id]);
});

test("the workspace-local probe records only protocol metadata", (t) => {
  const prepared = spawnSync(process.execPath, [probe, "prepare"], { encoding: "utf8" });
  assert.equal(prepared.status, 0, prepared.stderr);
  const root = prepared.stdout.trim();
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const hooks = join(root, ".agents", "hooks.json");
  const group = json(hooks)["agent-link-probe"];
  const started = shell(group.SessionStart[0].command, dirname(hooks), JSON.stringify({ lastUserInput: "secret!" }));
  assert.equal(started.status, 0, started.stderr);
  const message = JSON.parse(started.stdout).injectSteps[0].systemMessage;
  assert.equal(message.systemMessage, "");
  assert.match(message.metadata.user_markdown, /UI probe/);
  const result = shell(group.PreInvocation[0].command, dirname(hooks), JSON.stringify({ invocationNum: 0, initialNumSteps: 8,
    transcriptPath: join(root, "conversation", "transcript.jsonl"), lastUserInput: "secret!", conversationId: "private-id" }));
  assert.deepEqual(JSON.parse(result.stdout), {});
  const stop = shell(group.Stop[0].command, dirname(hooks), JSON.stringify({ terminationReason: "NO_TOOL_CALL", executionNum: 1 }));
  assert.deepEqual(JSON.parse(stop.stdout), { decision: "stop" });
  const records = read(join(root, "events.jsonl"));
  assert.doesNotMatch(records, /secret|private-id|conversation/);
  const [, pre, stopped] = records.trim().split("\n").map(JSON.parse);
  assert.deepEqual(pre, { event: "PreInvocation", invocationNum: 0, initialNumSteps: 8, executionNum: null,
    transcriptJsonl: true, transcriptFile: "primary" });
  assert.equal(stopped.terminationReason, "NO_TOOL_CALL");
  assert.equal(stopped.executionNum, 1);
});
